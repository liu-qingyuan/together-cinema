#!/usr/bin/env python3
"""Opt-in install/upgrade check on a disposable local deployment.

Requires Playwright, Chrome and FFmpeg. Uploads a generated MKV, waits for the real
converter, then plays its MP4 and checks an active subtitle in the browser.
Use --keep-upload to seed a temporary old-version volume; after updating through
./install.sh, rerun with --existing <output> to check that same film and subtitle.
Never use a personal deployment. No existing film is deleted or modified.
"""
import argparse
import asyncio
import json
import re
import subprocess
import tempfile
import uuid
from pathlib import Path
from urllib.parse import urlsplit

from playwright.async_api import async_playwright, expect


async def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('url')
    parser.add_argument('--channel', default='chrome')
    parser.add_argument('--keep-upload', action='store_true')
    parser.add_argument('--existing', help='Only a film generated by this script')
    args = parser.parse_args()
    url = urlsplit(args.url)
    if (url.scheme != 'http' or url.hostname not in ('localhost', '127.0.0.1')
            or not url.port or url.path not in ('', '/') or url.username or url.password):
        parser.error('Use an isolated loopback HTTP deployment')
    if args.existing and not re.fullmatch(r'[a-f0-9]{16}-runtime-layout-[a-f0-9]{32}\.mp4', args.existing):
        parser.error('--existing must name a generated runtime-layout film')
    base = args.url.rstrip('/')
    subtitle = 'Runtime layout: original subtitle survives.'
    uploaded = None
    async with async_playwright() as playwright:
        browser = await playwright.chromium.launch(channel=args.channel)
        page = await browser.new_page(base_url=base, locale='zh-CN')
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        try:
            await page.goto('/?room=L13' + uuid.uuid4().hex[:5].upper())
            await expect(page.locator('#connection')).to_contain_text('房主')
            job = None
            if args.existing:
                name = args.existing
            else:
                with tempfile.TemporaryDirectory() as directory:
                    root = Path(directory)
                    (root / 'caption.srt').write_text('1\n00:00:00,000 --> 00:01:00,000\n' + subtitle + '\n')
                    clip = root / ('runtime-layout-' + uuid.uuid4().hex + '.mkv')
                    subprocess.run(['ffmpeg', '-v', 'error', '-f', 'lavfi', '-i',
                                    'testsrc2=size=160x90:rate=10', '-f', 'lavfi', '-i',
                                    'sine=frequency=440', '-i', str(root / 'caption.srt'),
                                    '-t', '60', '-map', '0:v', '-map', '1:a', '-map', '2:s',
                                    '-c:v', 'mpeg4', '-q:v', '8', '-c:a', 'ac3', '-c:s', 'srt',
                                    '-metadata:s:s:0', 'language=eng', str(clip)], check=True)
                    response = await page.request.post('/api/upload', multipart={
                        'video': {'name': clip.name, 'mimeType': 'video/x-matroska', 'buffer': clip.read_bytes()}})
                    assert response.status == 202, await response.text()
                    job_id = (await response.json())['id']
                    async with asyncio.timeout(120):
                        while True:
                            response = await page.request.get('/api/conversions')
                            assert response.status == 200
                            job = next(j for j in (await response.json())['jobs'] if j['id'] == job_id)
                            assert job['status'] not in ('failed', 'cancelled'), job
                            if job['status'] == 'done':
                                name = uploaded = job['output']
                                break
                            await asyncio.sleep(.25)  # Poll the public job status, not browser timing.
                    assert job['mode'] == 'transcode', job
            await page.get_by_role('tab', name='片库', exact=True).click()
            await page.locator('#library').get_by_role('button', name=re.compile(re.escape(name.split('-', 1)[1]))).click()
            await page.wait_for_function("document.querySelector('#video').readyState >= 2")
            await page.locator('#videoStage').hover()
            await page.get_by_label('播放', exact=True).click()
            await page.wait_for_function("!video.paused && video.currentTime > 1")
            await page.wait_for_function('text => [...video.textTracks].some(t => t.mode === "showing" && [...(t.activeCues || [])].some(c => c.text === text))', arg=subtitle)
            manifest = await page.request.get('/api/subtitles/' + name)
            assert manifest.status == 200
            assert len((await manifest.json())['tracks']) == 1
            assert not errors, errors
            print(json.dumps({'film': name, 'existing_volume': bool(args.existing),
                              'conversion': job['mode'] if job else 'preserved',
                              'real_browser_playback': True, 'original_subtitle_active': True,
                              'browser_errors': errors}))
        finally:
            try:
                if uploaded and not args.keep_upload:
                    response = await page.request.delete('/api/library/' + uploaded)
                    assert response.status == 200, await response.text()
            finally:
                await browser.close()


if __name__ == '__main__':
    asyncio.run(main())
